def plot_img_and_mask(img, mask):
    import matplotlib.pyplot as plt  # imported lazily: only needed for --viz, not for serving
    classes = mask.max() + 1
    fig, ax = plt.subplots(1, classes + 1)
    ax[0].set_title('Input image')
    ax[0].imshow(img)
    for i in range(classes):
        ax[i + 1].set_title(f'Mask (class {i + 1})')
        ax[i + 1].imshow(mask == i)
    plt.xticks([]), plt.yticks([])
    plt.show()

def save_image_overlay(img,mask,path=None,epoch=None):
    color = np.array([0,255,0]) 
    colored_mask = np.zeros((mask.shape+(3,)))
    if mask.max()==1:
        mask[mask==1]=255
    
    colored_mask[mask==255]=color
    if img.shape[0] == 3:
        img = np.transpose(img,(1,2,0))
    if img.max()==1:
        img = (img*255)
    img = 0.5*img +0.5*colored_mask
    if path and epoch:
        name = os.path.join(path,f'result_{epoch}.jpg')
        Image.fromarray(img.astype(np.uint8)).save(name)
    else:
        return  Image.fromarray(img.astype(np.uint8))



